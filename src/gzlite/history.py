"""Read the embedded history of what each recorded commit's ``configure`` wrote.

``migrate`` uses this to tell untouched managed files from local edits in a project
that adopted an earlier gz-starter (or skills-first-starter) revision. The data file
``resources/release_history.json`` is generated by ``tools/build_release_history.py``
from every commit reachable from tag ``v0.13.0`` that has a release tag among its
ancestors, and from tagged gzlite releases for ``freshen``. Its format is documented
in ``resources/schemas/release-history.schema.json``.

Adopters recorded untagged revisions too (``windows-health`` records 0.3.2, which was
never tagged), and those commits' templates differ from the nearest tag's. So the
history holds one configure *snapshot* per distinct commit state, and each commit
maps to its own snapshot. Nothing here runs git.
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from dataclasses import dataclass, fields
from importlib.resources import files
from types import MappingProxyType
from typing import Any

SCHEMA_VERSION = 1
HISTORY_RESOURCE = "resources/release_history.json"
# A managed path entry is "<marker>:<path>" or a bare path (marker "always").
# Repository-relative paths never contain ":", which Windows forbids in names.
MARKERS = frozenset({"always", "if-absent", "merged", "merged-if-exists", "adr-local"})


class HistoryError(ValueError):
    """The history is unreadable or does not contain the requested revision."""


@dataclass(frozen=True, slots=True)
class ManagedPath:
    """One path a snapshot's ``configure`` wrote, and the condition it wrote it under.

    Conditions:
    ``always``: whole file, always written. ``if-absent``: written only when the
    file did not exist; project-owned after. ``merged``: host configuration with
    the starter's marketplace and plugin entries merged into existing content.
    ``merged-if-exists``: used instead of the host's ``merged`` path when it
    already existed (OpenCode ``opencode.jsonc``). ``adr-local``: written only when
    the lock's ``adr_policy.mode`` is ``local``.

    Content source, by path:
    ``AGENTS.skills-first.md`` is ``fragment_template`` (placeholders rendered when
    ``adr_placeholders``); ``.../skills/<update_skill>/SKILL.md`` is
    ``update_skill_template``; ``.agents/skills/<front_door_skill>/SKILL.md`` is
    ``front_door_skill_template``; ``if-absent:AGENTS.md`` is ``agents_md_template``;
    ``adr-local:`` is ``adr_policy_template`` (byte for byte). ``<state>/bundle.lock.json``
    has no template: it is generated JSON (``indent=2`` and a final newline) whose
    top-level keys are ``lock_keys``. ``merged`` paths have no template either.
    """

    path: str
    condition: str


@dataclass(frozen=True, slots=True)
class Release:
    """What ``configure`` wrote at one starter commit.

    ``version`` is the ``template_version`` that commit's ``bundle.json`` declares,
    which an untagged commit may share with no tag (0.3.2) or with a later tag.
    ``tag`` is the nearest release tag at or before the commit, for display.
    ``snapshot`` identifies the deduplicated configure state. Templates are raw
    text with ``{{...}}`` placeholders left in place; a caller renders them with
    the adopter's recorded revision.
    """

    version: str
    tag: str
    revision: str
    snapshot: str
    origin: str
    state_directory: str
    marketplace: str
    fragment_template: str
    update_skill: str | None
    update_skill_template: str | None
    adr_placeholders: bool
    hosts: tuple[str, ...]
    managed_paths: Mapping[str, tuple[str, ...]]
    front_door_skill: str | None
    front_door_skill_template: str | None
    agents_md_template: str
    lock_keys: tuple[str, ...]
    adr_policy_source: str | None
    adr_policy_template: str | None
    adr_policy_url: str | None

    def managed_entries(self, host: str) -> list[ManagedPath]:
        """Parse this snapshot's managed paths for ``host`` into path and condition."""
        if host not in self.managed_paths:
            raise HistoryError(f"{self.revision} ({self.version}) did not support host {host}")
        entries = []
        for entry in self.managed_paths[host]:
            condition, separator, path = entry.partition(":")
            entries.append(
                ManagedPath(path, condition) if separator else ManagedPath(entry, "always")
            )
        return entries


@dataclass(frozen=True, slots=True)
class Revision:
    """A starter commit's snapshot and its nearest release tag."""

    snapshot: str
    tag: str


@dataclass(frozen=True, slots=True)
class History:
    """Every release tag, every mapped starter commit, and their snapshots."""

    releases: tuple[Release, ...]
    revisions: Mapping[str, Revision]
    snapshots: Mapping[str, Mapping[str, Any]]

    def release_for(self, revision: str) -> Release:
        """Return what ``configure`` wrote at ``revision``, a commit in the starter's history."""
        entry = self.revisions.get(revision)
        if entry is None:
            raise HistoryError(f"revision {revision} is not in the starter's release history")
        return _build(self.snapshots[entry.snapshot], entry.tag, revision, entry.snapshot)


IDENTITY_FIELDS = frozenset({"tag", "revision", "snapshot"})
SNAPSHOT_FIELDS = frozenset(field.name for field in fields(Release)) - IDENTITY_FIELDS


def _build(snapshot: Mapping[str, Any], tag: str, revision: str, ident: str) -> Release:
    return Release(tag=tag, revision=revision, snapshot=ident, **snapshot)


def _snapshot(ident: str, data: object) -> Mapping[str, Any]:
    """Validate one snapshot and freeze its containers."""
    if not isinstance(data, dict) or set(data) != SNAPSHOT_FIELDS:
        raise HistoryError(f"snapshot {ident} has unexpected fields")
    hosts, managed = data["hosts"], data["managed_paths"]
    if not isinstance(managed, dict) or not isinstance(hosts, list) or set(managed) != set(hosts):
        raise HistoryError(f"snapshot {ident} managed paths do not match its hosts")
    frozen = dict(data)
    frozen["hosts"] = tuple(hosts)
    frozen["lock_keys"] = tuple(data["lock_keys"])
    frozen["managed_paths"] = MappingProxyType({h: tuple(v) for h, v in managed.items()})
    release = _build(frozen, "", "", ident)
    for host in release.hosts:
        for entry in release.managed_entries(host):
            if entry.condition not in MARKERS or not entry.path:
                raise HistoryError(f"snapshot {ident} has an invalid managed path {entry}")
    return MappingProxyType(frozen)


def parse_history(text: str) -> History:
    """Validate the history document's shape and build the lookup objects."""
    try:
        data = json.loads(text)
    except ValueError as error:
        raise HistoryError(f"release history is not valid JSON: {error}") from error
    expected = {"schema_version", "snapshots", "releases", "revisions"}
    if not isinstance(data, dict) or set(data) != expected:
        raise HistoryError("release history has unexpected top-level keys")
    if data["schema_version"] != SCHEMA_VERSION:
        raise HistoryError("unsupported release history schema")
    snapshots = {ident: _snapshot(ident, item) for ident, item in data["snapshots"].items()}
    revisions = {}
    for commit, entry in data["revisions"].items():
        if not isinstance(entry, dict) or set(entry) != {"snapshot", "tag"}:
            raise HistoryError(f"revision {commit} has unexpected fields")
        if entry["snapshot"] not in snapshots:
            raise HistoryError(f"revision {commit} names an unknown snapshot")
        revisions[commit] = Revision(entry["snapshot"], entry["tag"])
    releases = []
    for entry in data["releases"]:
        if not isinstance(entry, dict) or set(entry) != IDENTITY_FIELDS:
            raise HistoryError("release entry has unexpected fields")
        if revisions.get(entry["revision"]) != Revision(entry["snapshot"], entry["tag"]):
            raise HistoryError(f"release {entry['tag']} disagrees with its revision entry")
        releases.append(
            _build(snapshots[entry["snapshot"]], entry["tag"], entry["revision"], entry["snapshot"])
        )
    tags = {release.tag for release in releases}
    if not {entry.tag for entry in revisions.values()} <= tags:
        raise HistoryError("release history maps revisions to unknown releases")
    return History(tuple(releases), MappingProxyType(revisions), MappingProxyType(snapshots))


def load_history() -> History:
    """Load the history embedded in this installed package."""
    text = files("gzlite").joinpath(HISTORY_RESOURCE).read_text(encoding="utf-8")
    return parse_history(text)
